"""Writes reports/RESULTS.md and comparison figures from the saved metrics."""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

import config

ORDER = ["k-Shape + LightGBM (proposed)", "Single global LightGBM",
         "Naive: 28-day average", "Naive: same day last week"]


def _md(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _table(m: pd.DataFrame, level: str, target: str = "total") -> pd.DataFrame:
    t = m[(m["level"] == level) & (m["target"] == target)]
    if "cluster" in t:
        t = t[t["cluster"].astype(str) == "all"]
    t = t.set_index("model").loc[[o for o in ORDER if o in set(t["model"])]]
    return t[["MAE", "RMSE", "SMAPE_%", "R2", "Bias"]].reset_index()


def build_report() -> str:
    reg = json.loads(config.REGISTRY_JSON.read_text())
    one = pd.read_csv(config.REPORTS_DIR / "metrics_one_step.csv")
    rec_path = config.REPORTS_DIR / "metrics_recursive.csv"
    rec = pd.read_csv(rec_path) if rec_path.exists() else None
    prof = pd.read_csv(config.REPORTS_DIR / "cluster_profiles.csv")

    # Figure: MAE by cluster, beat-week level, total crime
    cl = one[(one["target"] == "total") & (one["level"] == "beat-week") & (one["cluster"] != "all")]
    piv = cl.pivot(index="cluster", columns="model", values="MAE")[[o for o in ORDER if o in cl["model"].unique()]]
    ax = piv.plot.bar(figsize=(10, 4.5), rot=0)
    ax.set(title="Weekly beat-level MAE by cluster (test period, lower is better)",
           xlabel="k-Shape cluster", ylabel="MAE (crimes / beat / week)")
    ax.grid(axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(config.FIGURES_DIR / "mae_by_cluster.png", dpi=150)
    plt.close()

    # Figure: per crime type MAE, beat-week
    ty = one[(one["level"] == "beat-week") & (one["cluster"] == "all") & (one["target"] != "total")]
    piv = ty.pivot(index="target", columns="model", values="MAE")[[o for o in ORDER if o in ty["model"].unique()]]
    ax = piv.sort_values(ORDER[0]).plot.barh(figsize=(10, 6))
    ax.set(title="Weekly beat-level MAE by crime type (test period)", xlabel="MAE")
    ax.grid(axis="x", alpha=0.3)
    plt.tight_layout()
    plt.savefig(config.FIGURES_DIR / "mae_by_crime_type.png", dpi=150)
    plt.close()

    type_tbl = (ty[ty["model"] == ORDER[0]][["target", "MAE", "RMSE", "SMAPE_%", "R2"]]
                .merge(ty[ty["model"] == "Naive: 28-day average"][["target", "MAE"]]
                       .rename(columns={"MAE": "MAE_naive28"}), on="target"))
    type_tbl["improvement_vs_naive_%"] = 100 * (1 - type_tbl["MAE"] / type_tbl["MAE_naive28"])

    parts = [
        "# Results",
        "",
        f"*Auto-generated by `scripts/run_pipeline.py`.* Training data {reg['start_date']} to "
        f"{pd.Timestamp(reg['test_start']) - pd.Timedelta(days=1):%Y-%m-%d}; held-out test period "
        f"{reg['test_start']} to {reg['data_end']}. "
        f"{len(reg['beat_codes'])} police beats, {reg['n_clusters']} k-Shape clusters, "
        f"{reg['n_clusters'] * len(reg['targets'])} specialist LightGBM models "
        f"({reg['n_clusters']} total + {reg['n_clusters']}x{len(reg['types'])} crime types).",
        "",
        "## 1. k-Shape clusters",
        "",
        _md(prof[["Cluster", "ClusterName", "n_beats", "mean_daily_crimes", "weekend_ratio",
                  "summer_winter_ratio"]]),
        "",
        "![elbow](figures/elbow_kshape.png)",
        "![shapes](figures/cluster_shapes.png)",
        "",
        "## 2. Overall crime total - one day ahead",
        "",
        "Each model forecasts tomorrow using data up to today.",
        "",
        "**Beat-day level** (one beat, one day):",
        "",
        _md(_table(one, "beat-day")),
        "",
        "**Beat-week level** (one beat, 7-day total - the planning unit for weekly patrol rosters):",
        "",
        _md(_table(one, "beat-week")),
        "",
        "**City-day level** (all beats summed):",
        "",
        _md(_table(one, "city-day")),
        "",
        "![mae by cluster](figures/mae_by_cluster.png)",
        "",
    ]
    if rec is not None:
        r = rec[rec["level"].isin(["beat-day", "beat-week"])]
        parts += [
            "## 3. Overall crime total - 7-day recursive forecast",
            "",
            "Forecasts start on each week of the test period and run 7 days ahead. Each day's "
            "forecast is used as input for the next day, exactly as the dashboard does it.",
            "",
            "**Beat-day:**",
            "",
            _md(_table(r, "beat-day")),
            "",
            "**Beat-week (7-day totals):**",
            "",
            _md(_table(r, "beat-week")),
            "",
        ]
    parts += [
        "## 4. Crime types (beat-week level, one day ahead)",
        "",
        _md(type_tbl),
        "",
        "![mae by type](figures/mae_by_crime_type.png)",
        "",
        "## 5. Explainability (SHAP)",
        "",
        "![shap heatmap](figures/shap_importance_heatmap.png)",
        "",
        "Per-cluster SHAP summary plots: `figures/shap_summary_cluster_<k>.png`.",
        "",
        "## Reading these numbers",
        "",
        "* Daily crime counts per beat are small (about 1-4) and largely random. Even a perfect "
        "model of the *expected* count cannot get beat-day R2 close to 1, so the useful comparison "
        "is against the baselines, and at the beat-week level.",
        "* \"k-Shape + LightGBM\" vs \"single global LightGBM\" tests the paper's main claim that "
        "pattern-specific models help. Report whichever way it comes out.",
    ]
    text = "\n".join(parts) + "\n"
    (config.REPORTS_DIR / "RESULTS.md").write_text(text, encoding="utf-8")
    return text
